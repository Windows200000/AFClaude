"""The API schema and the frontend's TS types, generated from api_types.py + routes.ENDPOINTS
(design §4 "API types", D-209; docs/phase6a_plan.md W2). No codegen package: pydantic emits the
JSON Schema, and the TS generator below covers exactly the subset pydantic emits for our models;
any other construct is an error, never a guessed type.

  python -m dashboard.codegen           write dashboard/schema.json and dashboard/web/src/api/types.gen.ts
  python -m dashboard.codegen --check   exit 1 when a committed file differs from a fresh generation

test_dashboard runs --check, so a model change without regenerating fails the tests.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
from collections.abc import Sequence
from typing import TYPE_CHECKING, Any

from pydantic.json_schema import JsonSchemaMode, models_json_schema

from dashboard.api_types import ErrorResponse, Model
from dashboard.errors import ERROR_CODES

if TYPE_CHECKING:
    from dashboard.routes import Endpoint

HERE = os.path.dirname(os.path.abspath(__file__))
SCHEMA_PATH = os.path.join(HERE, "schema.json")
TS_PATH = os.path.join(HERE, "web", "src", "api", "types.gen.ts")
REF = "#/components/schemas/{model}"
GENERATED = "Generated by `python -m dashboard.codegen` from dashboard/api_types.py and dashboard/routes.py. Do not edit."

# JSON Schema keywords that only annotate or constrain a value: no effect on the TS type
_ANNOTATIONS = frozenset({"title", "description", "default", "examples", "format", "pattern", "minLength",
                          "maxLength", "minimum", "maximum", "exclusiveMinimum", "exclusiveMaximum",
                          "minItems", "maxItems", "uniqueItems", "readOnly", "writeOnly", "deprecated"})
_STRUCTURE = frozenset({"$ref", "anyOf", "oneOf", "const", "enum", "type", "items", "properties", "required",
                        "additionalProperties", "prefixItems"})
JSON_VALUE_TS = ("string | number | boolean | null | readonly JsonValue[] | "
                 "{ readonly [key: string]: JsonValue }")


class UnsupportedSchema(ValueError):
    pass


# --- OpenAPI ----------------------------------------------------------------------------------

def openapi(endpoints: Sequence[Endpoint]) -> dict[str, Any]:
    """The OpenAPI 3.1 document of `endpoints` (schemas: JSON Schema 2020-12 from pydantic)."""
    wanted: list[tuple[type[Model], JsonSchemaMode]] = []
    for ep in endpoints:
        if ep.request is not None:
            wanted.append((ep.request, "validation"))
        wanted.append((ep.response, "serialization"))
    wanted.append((ErrorResponse, "serialization"))
    unique = list(dict.fromkeys(wanted))
    refs, top = models_json_schema(unique, ref_template=REF)
    error_ref = refs[(ErrorResponse, "serialization")]

    def content(ref: Any) -> dict[str, Any]:
        return {"application/json": {"schema": ref}}

    paths: dict[str, Any] = {}
    for ep in endpoints:
        responses: dict[str, Any] = {str(s): {"description": ep.summary, "content": content(refs[(ep.response, "serialization")])}
                                     for s in ep.statuses}
        responses["default"] = {"description": "error (the one error shape, §8)", "content": content(error_ref)}
        op: dict[str, Any] = {"operationId": ep.name, "summary": ep.summary, "x-access": ep.access,
                              "responses": responses}
        if ep.request is not None:
            op["requestBody"] = {"required": True, "content": content(refs[(ep.request, "validation")])}
        if ep.idempotent:
            op["parameters"] = [{"name": "Idempotency-Key", "in": "header", "required": True,
                                 "schema": {"type": "string", "format": "uuid"}}]
        paths.setdefault(ep.path, {})[ep.method.lower()] = op
    return {"openapi": "3.1.0",
            "info": {"title": "AFClaude dashboard API", "version": "1"},
            "paths": paths,
            "components": {"schemas": top.get("$defs", {})}}


def schema_text(doc: dict[str, Any]) -> str:
    return json.dumps(doc, indent=1, sort_keys=True, ensure_ascii=False) + "\n"


# --- TypeScript -------------------------------------------------------------------------------

def ts_name(name: str) -> str:
    out = re.sub(r"[^A-Za-z0-9_]", "_", name)
    if not re.match(r"[A-Za-z_]", out):
        raise UnsupportedSchema(f"schema name {name!r} is not a TS identifier")
    return out


def _paren(t: str) -> str:
    return f"({t})" if " | " in t else t


def ts_type(schema: Any, indent: str = "") -> str:
    """The TS type of one JSON Schema (the subset pydantic emits for our models)."""
    if not isinstance(schema, dict):
        raise UnsupportedSchema(f"not a schema: {schema!r}")
    unknown = set(schema) - _ANNOTATIONS - _STRUCTURE
    if unknown:
        raise UnsupportedSchema(f"unsupported JSON Schema keywords {sorted(unknown)}")
    if not set(schema) & _STRUCTURE:
        return "JsonValue"                               # {} (pydantic's JsonValue / Any)
    if "$ref" in schema:
        ref = schema["$ref"]
        if not isinstance(ref, str) or not ref.startswith("#/components/schemas/"):
            raise UnsupportedSchema(f"unsupported $ref {ref!r}")
        return ts_name(ref.rsplit("/", 1)[1])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return " | ".join(dict.fromkeys(ts_type(s, indent) for s in schema[key]))
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    t = schema.get("type")
    if isinstance(t, list):
        return " | ".join(ts_type({**schema, "type": x}, indent) for x in t)
    if t == "string":
        return "string"
    if t in ("integer", "number"):
        return "number"
    if t == "boolean":
        return "boolean"
    if t == "null":
        return "null"
    if t == "array":
        if "prefixItems" in schema:
            items = ", ".join(ts_type(s, indent) for s in schema["prefixItems"])
            return f"readonly [{items}]"
        if "items" not in schema:
            raise UnsupportedSchema("an array without items")
        return f"readonly {_paren(ts_type(schema['items'], indent))}[]"
    if t == "object":
        props = schema.get("properties")
        extra = schema.get("additionalProperties")
        if props is None:
            if isinstance(extra, dict):
                return f"{{ readonly [key: string]: {ts_type(extra, indent)} }}"
            raise UnsupportedSchema("an object without properties or a typed additionalProperties")
        if extra not in (None, False):
            raise UnsupportedSchema("an object with both properties and additionalProperties")
        return _ts_object(schema, indent)
    raise UnsupportedSchema(f"unsupported schema {schema!r}")


def _ts_object(schema: dict[str, Any], indent: str) -> str:
    required = set(schema.get("required", []))
    inner = indent + "  "
    lines = ["{"]
    for prop, sub in schema["properties"].items():
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", prop):
            raise UnsupportedSchema(f"property name {prop!r} is not a TS identifier")
        opt = "" if prop in required else "?"
        lines.append(f"{inner}readonly {prop}{opt}: {ts_type(sub, inner)};")
    lines.append(indent + "}")
    return "\n".join(lines)


def _doc_comment(text: str | None) -> list[str]:
    if not text:
        return []
    body = [" * " + line.rstrip() if line.strip() else " *" for line in text.strip().splitlines()]
    return ["/**", *[b.replace("*/", "* /") for b in body], " */"]


def typescript(doc: dict[str, Any], endpoints: Sequence[Endpoint]) -> str:
    """The TS module: one type per schema, the error codes and the endpoint table."""
    out = [f"// {GENERATED}", "", f"export type JsonValue = {JSON_VALUE_TS};", ""]
    out.append("export const ERROR_CODES = [")
    out += [f"  {json.dumps(c)}," for c in ERROR_CODES]
    out += ["] as const;", "export type ErrorCode = (typeof ERROR_CODES)[number];", ""]
    schemas: dict[str, Any] = doc["components"]["schemas"]
    for name in sorted(schemas):
        schema = schemas[name]
        if name == "JsonValue" and ts_type(schema) == "JsonValue":
            continue
        out += _doc_comment(schema.get("description"))
        if schema.get("type") == "object" and "properties" in schema:
            out.append(f"export interface {ts_name(name)} {ts_type(schema)}")
        else:
            out.append(f"export type {ts_name(name)} = {ts_type(schema)};")
        out.append("")
    out.append("export const ENDPOINTS = {")
    for ep in endpoints:
        out.append(f"  {ep.name}: {{ method: {json.dumps(ep.method)}, path: {json.dumps(ep.path)}, "
                   f"access: {json.dumps(ep.access)}, idempotent: {'true' if ep.idempotent else 'false'} }},")
    out += ["} as const;", "export type EndpointName = keyof typeof ENDPOINTS;", ""]
    out.append("export interface EndpointTypes {")
    for ep in endpoints:
        op = doc["paths"][ep.path][ep.method.lower()]
        req = ts_type(op["requestBody"]["content"]["application/json"]["schema"]) if ep.request else "null"
        res = ts_type(op["responses"][str(ep.statuses[0])]["content"]["application/json"]["schema"])
        out.append(f"  readonly {ep.name}: {{ readonly request: {req}; readonly response: {res} }};")
    out += ["}", ""]
    return "\n".join(out)


# --- CLI --------------------------------------------------------------------------------------

def generate() -> dict[str, str]:
    """{path: text} of every generated file."""
    from dashboard.routes import ENDPOINTS
    doc = openapi(ENDPOINTS)
    return {SCHEMA_PATH: schema_text(doc), TS_PATH: typescript(doc, ENDPOINTS)}


def stale() -> list[str]:
    """The generated files whose committed text differs from a fresh generation."""
    out = []
    for path, text in generate().items():
        try:
            with open(path, encoding="utf-8") as fh:
                if fh.read() == text:
                    continue
        except FileNotFoundError:
            pass
        out.append(os.path.relpath(path, os.path.dirname(HERE)))
    return out


def main(argv: Sequence[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="python -m dashboard.codegen", description=__doc__.split("\n\n")[0] if __doc__ else None)
    ap.add_argument("--check", action="store_true", help="only compare; exit 1 when a file is stale")
    args = ap.parse_args(argv)
    if args.check:
        bad = stale()
        for path in bad:
            print(f"stale: {path} (run: python -m dashboard.codegen)", file=sys.stderr)
        return 1 if bad else 0
    for path, text in generate().items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(text)
        print(f"wrote {os.path.relpath(path, os.path.dirname(HERE))}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
